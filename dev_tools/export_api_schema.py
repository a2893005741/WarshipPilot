"""Export the WebSocket contract alongside the frontend client, as in ALAS."""
import json
from pathlib import Path
from module.api.protocol import RequestEnvelope
from module.api.socket import GET_ACTIONS, POST_ACTIONS, METHODS


def export():
    folder = Path(__file__).resolve().parents[1] / 'frontend/src/api'
    methods = sorted(GET_ACTIONS | POST_ACTIONS | set(METHODS))
    contract = {'version': 1, 'path': '/api/v1/ws',
                'request': RequestEnvelope.model_json_schema(), 'methods': methods}
    (folder / 'contract.json').write_text(json.dumps(contract, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    source = '// Generated by python -m dev_tools.export_api_schema.\n'
    source += 'export const API_WS_PATH = "/api/v1/ws";\n'
    source += 'export type ApiMethod = ' + ' | '.join(json.dumps(method) for method in methods) + ';\n'
    (folder / 'generated.ts').write_text(source, encoding='utf-8')


if __name__ == '__main__':
    export()
